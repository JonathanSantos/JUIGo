// Comando chain gera os métodos ENCADEÁVEIS comuns a todo widget — Grow,
// Centered, AtStart, AtEnd, Tooltip, SetDisabled e BindDisabled — para cada
// tipo concreto, devolvendo o próprio tipo.
//
// Go não deixa um método do BaseWidget embutido devolver o tipo que o
// embute, então a única forma de ter `NewInput("…").Grow(1)` em toda a
// biblioteca, com o tipo preservado, é declarar o método em cada widget.
// Este gerador faz isso a partir de uma lista — um teste do pacote widget
// garante que nenhum widget exportado fique de fora.
//
// Uso (a partir da raiz do módulo):
//
//	go generate ./...
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"log"
	"os"
	"path/filepath"
)

// target descreve um arquivo gerado: pacote, caminho e tipos (como aparecem
// no receptor — genéricos levam os parâmetros de tipo). focusable são os
// tipos que participam do foco de teclado e ganham também OnFocus/OnBlur.
type target struct {
	pkg       string
	path      string
	types     []string
	focusable []string
}

var targets = []target{
	{pkg: "widget", path: "widget/chain_gen.go", types: []string{
		"Button", "Calendar", "Card", "Checkbox", "CodeEditor", "Container",
		"Divider", "Dropdown", "Grid", "HBox", "Image", "Input", "Label",
		"List[W]", "MenuBar", "Navigator", "ProgressBar", "Radio", "Scroll",
		"Sized", "Slider", "Spacer", "SplitPane", "Table", "Tabs", "Text",
		"TextArea", "Tree[ID, W]", "VBox",
	}, focusable: []string{
		"Button", "Checkbox", "CodeEditor", "Dropdown", "Input", "Radio",
		"Slider", "SplitPane", "Tabs", "TextArea", "Tree[ID, W]",
	}},
	{pkg: "chart", path: "chart/chain_gen.go", types: []string{"Bars", "Line", "Spark"}},
	{pkg: "quick", path: "quick/chain_gen.go", types: []string{"FormView"}},
}

func main() {
	root := "."
	if len(os.Args) > 1 {
		root = os.Args[1]
	}
	for _, t := range targets {
		src, err := render(t)
		if err != nil {
			log.Fatalf("chain: %s: %v", t.path, err)
		}
		if err := os.WriteFile(filepath.Join(root, t.path), src, 0o644); err != nil {
			log.Fatalf("chain: %v", err)
		}
	}
}

// render monta e formata o arquivo de um target.
func render(t target) ([]byte, error) {
	var b bytes.Buffer
	q := "" // qualificador do pacote widget fora dele
	fmt.Fprintf(&b, "// Code generated by internal/gen/chain; DO NOT EDIT.\n\npackage %s\n\n", t.pkg)
	if t.pkg == "widget" {
		b.WriteString("import \"github.com/JonathanSantos/JUIGo/state\"\n\n")
	} else {
		q = "widget."
		b.WriteString("import (\n\t\"github.com/JonathanSantos/JUIGo/state\"\n\t\"github.com/JonathanSantos/JUIGo/widget\"\n)\n\n")
	}
	for _, typ := range t.types {
		fmt.Fprintf(&b, methods, typ, q)
	}
	for _, typ := range t.focusable {
		fmt.Fprintf(&b, focusMethods, typ)
	}
	return format.Source(b.Bytes())
}

// methods é o molde por tipo: %[1]s é o tipo do receptor, %[2]s o
// qualificador do pacote widget.
const methods = `// Grow marca o widget para EXPANDIR no eixo principal do VBox/HBox com o
// peso dado (0 volta ao tamanho preferido). Encadeável.
func (w *%[1]s) Grow(weight int) *%[1]s { return %[2]sGrow(w, weight) }

// Centered posiciona o widget no eixo transversal do box com o tamanho
// preferido, centralizado (o padrão é esticar). Encadeável.
func (w *%[1]s) Centered() *%[1]s { return %[2]sCentered(w) }

// AtStart posiciona o widget no eixo transversal com o tamanho preferido,
// alinhado ao início (esquerda no VBox, topo no HBox). Encadeável.
func (w *%[1]s) AtStart() *%[1]s { return %[2]sAtStart(w) }

// AtEnd posiciona o widget no eixo transversal com o tamanho preferido,
// alinhado ao fim (direita no VBox, base no HBox). Encadeável.
func (w *%[1]s) AtEnd() *%[1]s { return %[2]sAtEnd(w) }

// Tooltip define o texto de dica exibido quando o ponteiro pausa sobre o
// widget ("" remove). Encadeável.
func (w *%[1]s) Tooltip(text string) *%[1]s { return %[2]sTooltip(w, text) }

// SetDisabled habilita/desabilita o widget (e a subárvore) para interação
// e agenda um redesenho. Encadeável.
func (w *%[1]s) SetDisabled(v bool) *%[1]s {
	w.BaseWidget.SetDisabled(v)
	return w
}

// BindDisabled vincula o estado desabilitado ao State: true desabilita.
// Encadeável.
func (w *%[1]s) BindDisabled(s *state.State[bool]) *%[1]s { return %[2]sBindDisabled(w, s) }

`

// focusMethods é o molde dos callbacks de foco: %[1]s é o tipo do receptor.
const focusMethods = `// OnFocus define o callback chamado quando o widget ganha o foco de
// teclado. Encadeável.
func (w *%[1]s) OnFocus(fn func()) *%[1]s {
	w.setFocusCallbacks(fn, nil)
	return w
}

// OnBlur define o callback chamado quando o widget perde o foco de teclado
// — útil para validação "touched" (ver juigo/form). Encadeável.
func (w *%[1]s) OnBlur(fn func()) *%[1]s {
	w.setFocusCallbacks(nil, fn)
	return w
}

`
